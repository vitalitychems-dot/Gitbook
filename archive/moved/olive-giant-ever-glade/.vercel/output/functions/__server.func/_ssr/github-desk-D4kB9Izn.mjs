var SECRET = /SESSION_SECRET|BEGIN [A-Z ]*PRIVATE KEY|AKIA[0-9A-Z]{16}|ghp_[A-Za-z0-9]|github_pat_|xox[baprs]-|sk-[A-Za-z0-9]{10,}/;
function noteAllowed(text) {
	const body = text.trim();
	if (body.length < 2 || body.length > 12e3) return "The note must stay between 2 and 12000 characters.";
	if (SECRET.test(body)) return "That note contains a secret and was not written.";
	return null;
}
async function gh(args) {
	const { execFile } = await import("node:child_process");
	const bins = ["/usr/local/bin/gh", "gh"];
	let last = "gh was not found on this machine.";
	for (const bin of bins) {
		const result = await new Promise((resolve) => {
			execFile(bin, args, {
				timeout: 2e4,
				maxBuffer: 2e6,
				env: {
					...process.env,
					PATH: `/usr/local/bin:/usr/bin:${process.env.PATH ?? ""}`
				}
			}, (error, stdout, stderr) => {
				resolve({
					code: error ? 1 : 0,
					out: `${stdout}${stderr}`.replace(/ghu_\S+/g, "ghu_redacted").trim()
				});
			});
		});
		if (result.code === 0) return result;
		last = result.out || last;
	}
	return {
		code: 1,
		out: last.slice(0, 280)
	};
}
