async function githubToken() {
	const { execFile } = await import("node:child_process");
	const { writeFile } = await import("node:fs/promises");
	const fromGh = await new Promise((resolve) => {
		execFile("/usr/local/bin/gh", ["auth", "token"], {
			timeout: 1e4,
			env: {
				...process.env,
				HOME: "/root",
				PATH: "/usr/local/bin:/usr/bin"
			}
		}, (error, stdout) => resolve(error ? "" : stdout.trim()));
	});
	if (fromGh && !fromGh.includes(" ")) {
		try {
			await writeFile("/tmp/tessera-gh-token", fromGh, { mode: 384 });
		} catch {}
		return fromGh;
	}
	const fromEnv = process.env.GH_TOKEN?.trim() || process.env.GITHUB_TOKEN?.trim() || "";
	if (fromEnv && !fromEnv.includes(" ")) return fromEnv;
	const { readFile } = await import("node:fs/promises");
	try {
		const stored = (await readFile("/tmp/tessera-gh-token", "utf8")).trim();
		if (stored && !stored.includes(" ")) return stored;
	} catch {}
	return "";
}
async function githubApi(path, init) {
	const token = await githubToken();
	const headers = {
		Accept: "application/vnd.github+json",
		"User-Agent": "tessera-chamber"
	};
	if (token) headers.Authorization = `Bearer ${token}`;
	const res = await fetch(`https://api.github.com${path}`, {
		method: init?.method ?? "GET",
		headers,
		body: init?.body
	});
	const text = (await res.text()).replace(/ghu_\S+|github_pat_\S+/g, "redacted");
	return {
		ok: res.ok,
		status: res.status,
		text: res.ok ? text : text.slice(0, 400)
	};
}
