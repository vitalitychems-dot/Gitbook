var readRepoFile = createServerFn({ method: "POST" }).validator((input) => input).handler(readRepoFile_createServerFn_handler, async ({ data }) => {
	const owner = data.owner.trim();
	const repo = data.repo.trim().replace(/\.git$/, "");
	const path = data.path.trim().replace(/^\/+/, "");
	if (!/^[\w.-]+$/.test(owner) || !/^[\w.-]+$/.test(repo) || !path || path.includes("..")) return {
		ok: false,
		error: "That repository path is not allowed."
	};
	const result = await gh([
		"api",
		`repos/${owner}/${repo}/contents/${path}`,
		"--jq",
		".content"
	]);
	if (result.code !== 0) return {
		ok: false,
		error: "That file could not be read."
	};
	let text = "";
	try {
		text = Buffer.from(result.out.replace(/\n/g, ""), "base64").toString("utf8");
	} catch {
		return {
			ok: false,
			error: "That file was not text."
		};
	}
	if (SECRET.test(text)) return {
		ok: false,
		error: "That file looks like a secret and was not returned."
	};
	return {
		ok: true,
		text: text.slice(0, 4e3),
		path: `${owner}/${repo}/${path}`
	};
});
